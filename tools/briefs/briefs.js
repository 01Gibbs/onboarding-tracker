// {{folder}} is filled from course.json in build.js, so each folder name is written once.
function gettingStarted({ app = true, bruno = true, maven = false, extra = [] } = {}) {
  const folder = "{{folder}}";
  const wrapper = maven ? "mvnw" : "gradlew";
  const run = maven ? "./mvnw spring-boot:run" : "./gradlew bootRun";
  return [
    { h2: "4. Getting started" },
    { p: "Every command runs from the day's `starter/` folder. From the course root:" },
    { code: `cd ${folder}/starter\nls ${wrapper.padEnd(15)}# "No such file or directory"? You're in the wrong folder.` },
    ...(app ? [{ p: "Start the app with `" + run + "` (port 8080; stop anything else on 8080 first). Reset its database at any time: stop it, `rm -rf data`, start it again." }] : []),
    ...(bruno ? [{ p: "In Bruno, **Open Collection** → `" + folder + "/bruno`, then pick the **Local** environment." }] : []),
    ...extra,
  ];
}

